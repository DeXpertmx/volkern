import { describe, it, expect, vi, beforeEach } from 'vitest';

// vi.mock del provisioner debe ir ANTES de cualquier import que lo use.
// Usamos vi.hoisted() para evitar el TDZ cuando el factory accede a constantes
// declaradas dentro del bloque describe.
const mocks = vi.hoisted(() => ({
  provisionTenant: vi.fn(),
}));

vi.mock('@/lib/provisioning/tenant-provisioner', () => ({
  // Re-exportar cualquier otro named export que el runner pueda importar.
  provisionTenant: mocks.provisionTenant,
  TenantProvisioningInput: class {},
  // Stubs mínimos para exports no-mocked (el runner no los usa pero
  // tipos del módulo los expone — TS no se queja en runtime).
  addTelegramChannelToTenant: vi.fn(),
}));

import {
  runBulkOnboarding,
  generateBulkPassword,
} from '@/lib/provisioning/partner-bulk-runner';
import type { BulkParsedRow } from '@/lib/insurance/csv-bulk';

function makeRow(overrides: Partial<BulkParsedRow> = {}): BulkParsedRow {
  return {
    rowNum: 1,
    empresa: 'Test SA',
    subdomain: 'test-sa',
    email: 'admin@test-sa.volkern.app',
    password: 'InitialPwd1',
    ...overrides,
  };
}

const BASE_ACTOR = { kind: 'system' as const, source: 'test' };

beforeEach(() => {
  mocks.provisionTenant.mockReset();
  // Default: éxito
  mocks.provisionTenant.mockImplementation(async () => ({
    success: true,
    tenantId: 'tenant_abc',
    chatwootAccountId: 100,
    telegramInboxId: null,
    telegramSkipped: true,
    moneda: 'MXN',
  }));
});

describe('runBulkOnboarding — dry-run', () => {
  it('1) dryRun=true no llama a provisionTenant y simula todas las filas', async () => {
    const rows = [makeRow({ rowNum: 1 }), makeRow({ rowNum: 2, subdomain: 'b' })];
    const result = await runBulkOnboarding({
      rows,
      autoGeneratedPasswords: { 1: 'pwd1', 2: 'pwd2' },
      dryRun: true,
      actor: BASE_ACTOR,
    });

    expect(mocks.provisionTenant).not.toHaveBeenCalled();
    expect(result.dryRun).toBe(true);
    expect(result.simulated).toBe(2);
    expect(result.created).toBe(0);
    expect(result.failed).toBe(0);
    expect(result.hadUnexpectedErrors).toBe(false);
    expect(result.report.every(r => r.status === 'simulated')).toBe(true);
  });

  it('2) dryRun incluye source EXPLICIT cuando la fila trae moneda', async () => {
    const rows = [makeRow({ rowNum: 1, moneda: 'EUR' })];
    const result = await runBulkOnboarding({
      rows,
      autoGeneratedPasswords: {},
      dryRun: true,
      actor: BASE_ACTOR,
    });
    expect(result.report[0].monedaInferenciaSource).toBe('EXPLICIT');
    expect(result.report[0].telegramStatus).toBe('n/a');
  });

  it('3) dryRun con Telegram muestra telegramStatus=simulated', async () => {
    const rows = [makeRow({
      rowNum: 1,
      telegramBotName: '@test_sa_bot',
      telegramBotToken: '123:abc',
    })];
    const result = await runBulkOnboarding({
      rows,
      autoGeneratedPasswords: {},
      dryRun: true,
      actor: BASE_ACTOR,
    });
    expect(result.report[0].telegramStatus).toBe('simulated');
  });
});

describe('runBulkOnboarding — happy path', () => {
  it('4) crea N tenants y reporta created N', async () => {
    const rows = Array.from({ length: 5 }, (_, i) =>
      makeRow({ rowNum: i + 1, subdomain: `slug${i + 1}` }),
    );
    const passwords = Object.fromEntries(rows.map(r => [r.rowNum, `pwd${r.rowNum}`]));
    const result = await runBulkOnboarding({
      rows,
      autoGeneratedPasswords: passwords,
      dryRun: false,
      actor: BASE_ACTOR,
    });

    expect(mocks.provisionTenant).toHaveBeenCalledTimes(5);
    expect(result.created).toBe(5);
    expect(result.failed).toBe(0);
    expect(result.ok).toBe(true);
    expect(result.report.every(r => r.status === 'created')).toBe(true);
  });

  it('5) llama a provisionTenant con subdomain/email lowercased + password del caller', async () => {
    const rows = [makeRow({
      rowNum: 1,
      subdomain: 'UPPER-CASE',
      email: 'Mixed@Case.COM',
    })];
    await runBulkOnboarding({
      rows,
      autoGeneratedPasswords: { 1: 'MySecretPwd1' },
      dryRun: false,
      actor: BASE_ACTOR,
    });
    const call = mocks.provisionTenant.mock.calls[0][0];
    expect(call.subdomain).toBe('upper-case');
    expect(call.email).toBe('mixed@case.com');
    expect(call.password).toBe('MySecretPwd1');
  });

  it('6) inyecta moneda + vertical cuando vienen en la fila', async () => {
    const rows = [makeRow({ rowNum: 1, moneda: 'EUR', vertical: 'insurance' })];
    await runBulkOnboarding({
      rows,
      autoGeneratedPasswords: {},
      dryRun: false,
      actor: BASE_ACTOR,
    });
    const call = mocks.provisionTenant.mock.calls[0][0];
    expect(call.moneda).toBe('EUR');
    expect(call.vertical).toBe('insurance');
  });

  it('7) inyecta telegram cuando vienen campos bot', async () => {
    const rows = [makeRow({
      rowNum: 1,
      telegramBotName: '@my_bot',
      telegramBotToken: '123456:abc',
    })];
    await runBulkOnboarding({
      rows,
      autoGeneratedPasswords: {},
      dryRun: false,
      actor: BASE_ACTOR,
    });
    const call = mocks.provisionTenant.mock.calls[0][0];
    expect(call.telegram).toEqual({ botName: '@my_bot', botToken: '123456:abc' });
  });

  it('8) NO inyecta telegram si falta alguno de botName/botToken', async () => {
    const rows = [makeRow({ rowNum: 1, telegramBotName: '@my_bot' /* sin token */ })];
    await runBulkOnboarding({
      rows,
      autoGeneratedPasswords: {},
      dryRun: false,
      actor: BASE_ACTOR,
    });
    const call = mocks.provisionTenant.mock.calls[0][0];
    expect(call.telegram).toBeUndefined();
  });
});

describe('runBulkOnboarding — error handling', () => {
  it('9) success=false mapea a error con código del provisioner', async () => {
    mocks.provisionTenant.mockResolvedValueOnce({
      success: false,
      error: { code: 'SUBDOMAIN_TAKEN', message: 'El subdominio ya existe' },
    });
    const result = await runBulkOnboarding({
      rows: [makeRow({ rowNum: 1 })],
      autoGeneratedPasswords: {},
      dryRun: false,
      actor: BASE_ACTOR,
    });
    expect(result.failed).toBe(1);
    expect(result.ok).toBe(false);
    expect(result.report[0].status).toBe('error');
    expect(result.report[0].errorCode).toBe('SUBDOMAIN_TAKEN');
    expect(result.report[0].errorMessage).toMatch(/ya existe/);
  });

  it('10) excepción no controlada → errorCode=UNEXPECTED + hadUnexpectedErrors=true', async () => {
    mocks.provisionTenant.mockRejectedValueOnce(new Error('Network down'));
    const result = await runBulkOnboarding({
      rows: [makeRow({ rowNum: 1 })],
      autoGeneratedPasswords: {},
      dryRun: false,
      actor: BASE_ACTOR,
    });
    expect(result.failed).toBe(1);
    expect(result.report[0].errorCode).toBe('UNEXPECTED');
    expect(result.report[0].errorMessage).toBe('Network down');
    expect(result.hadUnexpectedErrors).toBe(true);
  });

  it('11) MISSING_PASSWORD cuando no hay password en CSV ni del caller', async () => {
    const result = await runBulkOnboarding({
      rows: [makeRow({ rowNum: 1, password: undefined })],
      autoGeneratedPasswords: {},
      dryRun: false,
      actor: BASE_ACTOR,
    });
    expect(result.failed).toBe(1);
    expect(result.report[0].errorCode).toBe('MISSING_PASSWORD');
    // NO llamó al provisioner (fail-fast para no perder tiempo en I/O).
    expect(mocks.provisionTenant).not.toHaveBeenCalled();
  });

  it('12) errores de negocio NO marcan hadUnexpectedErrors', async () => {
    mocks.provisionTenant.mockResolvedValueOnce({
      success: false,
      error: { code: 'INVALID_EMAIL', message: 'email' },
    });
    const result = await runBulkOnboarding({
      rows: [makeRow({ rowNum: 1 })],
      autoGeneratedPasswords: {},
      dryRun: false,
      actor: BASE_ACTOR,
    });
    expect(result.report[0].errorCode).toBe('INVALID_EMAIL');
    expect(result.hadUnexpectedErrors).toBe(false);
  });
});

describe('runBulkOnboarding — concurrency pool', () => {
  it('13) processa N filas respetando concurrency=3', async () => {
    let inFlight = 0;
    let maxInFlight = 0;
    mocks.provisionTenant.mockImplementation(async () => {
      inFlight++;
      maxInFlight = Math.max(maxInFlight, inFlight);
      // Pequeño delay para que el pool pueda interleaving.
      await new Promise(resolve => setTimeout(resolve, 5));
      inFlight--;
      return {
        success: true, tenantId: 't', chatwootAccountId: 1,
        telegramInboxId: null, telegramSkipped: true, moneda: 'MXN',
      };
    });

    const rows = Array.from({ length: 9 }, (_, i) =>
      makeRow({ rowNum: i + 1, subdomain: `s${i + 1}` }),
    );
    const passwords = Object.fromEntries(rows.map(r => [r.rowNum, `pwd${r.rowNum}`]));
    const result = await runBulkOnboarding({
      rows,
      autoGeneratedPasswords: passwords,
      dryRun: false,
      concurrency: 3,
      actor: BASE_ACTOR,
    });

    expect(result.created).toBe(9);
    expect(mocks.provisionTenant).toHaveBeenCalledTimes(9);
    expect(maxInFlight).toBe(3);
  });

  it('14) concurrency fuera de rango se cap a 1..10', async () => {
    const calls = Array.from({ length: 5 }, (_, i) => makeRow({ rowNum: i + 1 }));
    await runBulkOnboarding({
      rows: calls,
      autoGeneratedPasswords: {},
      dryRun: false,
      concurrency: 100, // fuera de rango → cap a 10
      actor: BASE_ACTOR,
    });
    expect(mocks.provisionTenant).toHaveBeenCalledTimes(5);
  });
});

describe('runBulkOnboarding — empty input', () => {
  it('15) rows=[] devuelve ok=true con totales en cero', async () => {
    const result = await runBulkOnboarding({
      rows: [],
      autoGeneratedPasswords: {},
      dryRun: false,
      actor: BASE_ACTOR,
    });
    expect(result.ok).toBe(true);
    expect(result.total).toBe(0);
    expect(result.created).toBe(0);
    expect(result.failed).toBe(0);
    expect(result.report).toEqual([]);
    expect(mocks.provisionTenant).not.toHaveBeenCalled();
  });
});

describe('generateBulkPassword', () => {
  it('16) password de longitud correcta con al menos 1 mayúscula, 1 minúscula, 1 dígito', () => {
    for (let i = 0; i < 50; i++) {
      const pwd = generateBulkPassword(14);
      expect(pwd).toHaveLength(14);
      expect(pwd).toMatch(/[A-Z]/);
      expect(pwd).toMatch(/[a-z]/);
      expect(pwd).toMatch(/\d/);
      // Sin símbolos ambiguos.
      expect(pwd).not.toMatch(/[0O1lI]/);
    }
  });

  it('17) longitud custom se respeta', () => {
    const pwd = generateBulkPassword(20);
    expect(pwd).toHaveLength(20);
  });

  it('18) genera passwords distintos en 1000 iteraciones', () => {
    const set = new Set<string>();
    for (let i = 0; i < 1000; i++) set.add(generateBulkPassword(14));
    // Esperamos > 990 unique (3000 chars de entropía, colisión ~0).
    expect(set.size).toBeGreaterThan(990);
  });
});
