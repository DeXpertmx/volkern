/**
 * partner-bulk-runner — orquestador server-side reutilizable para crear
 * N tenants por fila (sin pasar por HTTP). Diseñado para que el endpoint
 * `/api/admin/partner-bulk` y futuras integraciones (CLI scripts, cron,
 * sales-ops pipelines) compartan exactamente la misma lógica que el
 * wizard web `app/admin/partner-onboarding/bulk/page.tsx`.
 *
 * Diferencia clave con el wizard: el runner llama a `provisionTenant`
 * directamente (sin HTTP), lo que evita el overhead de un fetch+JSON
 * por fila y permite dry-run sin mutar nada.
 *
 * Concurrencia default 3 (mismo número que el wizard y que el límite
 * seguro de Nexus para provisioning en paralelo).
 */

import { provisionTenant, type TenantProvisioningInput, type ProvisioningResult } from '@/lib/provisioning/tenant-provisioner';
import type { BulkParsedRow, BulkResultRow } from '@/lib/insurance/csv-bulk';

// ─── Tipos públicos ────────────────────────────────────────────────────────────

export type BulkActor =
  | { kind: 'user'; id: string; email?: string | null }
  | { kind: 'system'; source: string };

export type BulkStatus = 'created' | 'simulated' | 'error';

export interface BulkRunnerInput {
  /** Filas ya parseadas y validadas por `parseBulkCsv`. */
  rows: BulkParsedRow[];
  /** Mapa rowNum → password. Si la fila trae password en el CSV se reusa;
   *  si no, el caller pre-genera y la pasa por aquí. */
  autoGeneratedPasswords: Record<number, string>;
  /** Si true, simula cada fila (status='simulated') y no muta la BD. */
  dryRun: boolean;
  /** Default 3. Cap interno 1..10 para defenderse de caller hostil. */
  concurrency?: number;
  /** Para audit log + trazabilidad. */
  actor: BulkActor;
}

export interface BulkRunnerOutput {
  ok: boolean;
  dryRun: boolean;
  total: number;
  created: number;
  /** simulated cuenta como éxito para ok=true. failed son SOLO errores reales. */
  simulated: number;
  failed: number;
  report: BulkResultRow[];
  /** Detector rápido: ¿algún error con código UNEXPECTED? */
  hadUnexpectedErrors: boolean;
}

// ─── Auto-generador de password ────────────────────────────────────────────────

/**
 * Genera un password aleatorio seguro (14 chars). Mismo criterio que el
 * wizard: incluye al menos 1 mayúscula, 1 minúscula y 1 dígito; los símbolos
 * ambiguos (0/O, 1/l/I) se excluyen para que el operador pueda transcribirlo.
 *
 * MÁS: usa crypto.getRandomValues cuando está disponible (Node 19+) para
 * evitar Math.random. Mantiene Math.random como fallback para tests viejos.
 */
export function generateBulkPassword(length = 14): string {
  const upper = 'ABCDEFGHJKMNPQRSTUVWXYZ';
  const lower = 'abcdefghjkmnpqrstuvwxyz';
  const digits = '23456789';
  const safe = upper + lower + digits;

  // 3 posiciones garantizadas con clase conocida (upper, lower, digit)
  const base: string[] = [
    upper[secureRandom(upper.length)],
    lower[secureRandom(lower.length)],
    digits[secureRandom(digits.length)],
  ];
  for (let i = 3; i < length; i++) {
    base.push(safe[secureRandom(safe.length)]);
  }
  // shuffle determinista
  for (let i = base.length - 1; i > 0; i--) {
    const j = secureRandom(i + 1);
    [base[i], base[j]] = [base[j], base[i]];
  }
  return base.join('');
}

function secureRandom(maxExclusive: number): number {
  // .getRandomValues es síncrono y sirve para valores pequeños; cap a 1MB.
  try {
    const buf = new Uint32Array(1);
    crypto.getRandomValues(buf);
    return buf[0] % maxExclusive;
  } catch {
    return Math.floor(Math.random() * maxExclusive);
  }
}

// ─── Orquestador ───────────────────────────────────────────────────────────────

/**
 * Procesa una fila individual y la convierte en BulkResultRow.
 * Nunca lanza: los errores se mapean a `status='error' + errorCode`.
 */
async function processOneRow(
  row: BulkParsedRow,
  autoPasswords: Record<number, string>,
  dryRun: boolean,
): Promise<BulkResultRow> {
  const base: BulkResultRow = {
    rowNum: row.rowNum,
    empresa: row.empresa,
    subdomain: row.subdomain,
    email: row.email,
    moneda: row.moneda ?? 'MXN',
    status: 'pending',
  };

  if (dryRun) {
    return {
      ...base,
      status: 'simulated',
      telegramStatus: row.telegramBotName ? 'simulated' : 'n/a',
      monedaInferenciaSource: row.moneda ? 'EXPLICIT' : 'FALLBACK',
    };
  }

  const password = (autoPasswords[row.rowNum] ?? row.password ?? '').trim();
  if (!password) {
    return {
      ...base,
      status: 'error',
      errorCode: 'MISSING_PASSWORD',
      errorMessage: 'El caller no inyectó password y la fila no trae uno en el CSV.',
    };
  }

  // ─── Telegram viene en la fila del CSV (no en /api/tenants/create legacy) ──
  const hasTelegram = !!(row.telegramBotName && row.telegramBotToken);

  try {
    const result = await provisionTenant({
      empresa: row.empresa,
      subdomain: row.subdomain.toLowerCase(),
      email: row.email.toLowerCase(),
      password,
      ...(row.moneda ? { moneda: row.moneda as TenantProvisioningInput['moneda'] } : {}),
      ...(row.vertical ? { vertical: row.vertical as TenantProvisioningInput['vertical'] } : {}),
      ...(hasTelegram
        ? { telegram: { botName: row.telegramBotName!, botToken: row.telegramBotToken! } }
        : {}),
    } as unknown as TenantProvisioningInput) as ProvisioningResult;

    if (!result || result.success !== true) {
      return {
        ...base,
        status: 'error',
        errorCode: result?.error?.code ?? 'PROVISIONING_FAILED',
        errorMessage: result?.error?.message ?? 'provisionTenant devolvió success=false',
      };
    }

    // A partir de acá `result` está narrowed a TenantProvisioningSuccess
    // gracias al `if (!result || result.success !== true) return error`
    // de arriba. Lo casteamos explícitamente para que TS no se queje
    // con los campos opcionales (`moneda`, `telegramSkipped`) del branch
    // success — están garantizados existenciales en este punto.
    const success = result as Extract<ProvisioningResult, { success: true }>;

    return {
      ...base,
      status: 'created',
      tenantId: success.tenantId,
      chatwootAccountId: success.chatwootAccountId,
      telegramInboxId: success.telegramInboxId ?? null,
      telegramStatus: hasTelegram
        ? (success.telegramSkipped ? 'skipped' : success.telegramInboxId ? 'connected' : 'pending')
        : 'n/a',
      // `moneda` no está en TenantProvisioningSuccess: el provisioner la
      // respeta del input, así que la propagamos desde la fila parseada.
      // `monedaInferenciaSource` queda fijo = EXPLICIT cuando la trae el
      // CSV; FALLBACK (default MXN) cuando no (post-import-autofix puede
      // sobreescribirlo después, ver docs/MONEDA_TENANT_Y_PORTFOLIO.md).
      moneda: row.moneda ?? 'MXN',
      monedaInferenciaSource: row.moneda ? 'EXPLICIT' : 'FALLBACK',
    };
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : String(err);
    // Errores que escapan del provisioning son UNEXPECTED (no se
    // clasificaron arriba como códigos de negocio).
    return {
      ...base,
      status: 'error',
      errorCode: 'UNEXPECTED',
      errorMessage: message.slice(0, 280),
    };
  }
}

/**
 * Pool de workers que consumen `rows` con concurrencia limitada.
 * Devuelve report[] en orden de finalización (no de origen).
 */
export async function runBulkOnboarding(input: BulkRunnerInput): Promise<BulkRunnerOutput> {
  const concurrency = Math.max(1, Math.min(input.concurrency ?? 3, 10));
  const queue: BulkParsedRow[] = [...input.rows];
  const report: BulkResultRow[] = [];
  let created = 0;
  let simulated = 0;
  let failed = 0;
  let hadUnexpected = false;

  async function worker(): Promise<void> {
    while (queue.length > 0) {
      const row = queue.shift();
      if (!row) break;
      const r = await processOneRow(row, input.autoGeneratedPasswords, input.dryRun);
      if (r.status === 'created') created++;
      else if (r.status === 'simulated') simulated++;
      else {
        failed++;
        if (r.errorCode === 'UNEXPECTED') hadUnexpected = true;
      }
      report.push(r);
    }
  }

  const workers = Array.from({ length: concurrency }, () => worker());
  await Promise.all(workers);

  return {
    ok: failed === 0,
    dryRun: input.dryRun,
    total: input.rows.length,
    created,
    simulated,
    failed,
    report,
    hadUnexpectedErrors: hadUnexpected,
  };
}
