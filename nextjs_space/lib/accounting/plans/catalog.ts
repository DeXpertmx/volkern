export function getPlanAccounts(
  planType: PgcPlan,
  sector: SectorAdaptation = 'NINGUNO',
): AccountDef[] {
  const plans: Record<PgcPlan, AccountDef[]> = {
    NORMAL: PGC_NORMAL,
    PYMES: PGC_PYMES,
    MICRO: PGC_MICRO,
  }

  const base = plans[planType]
  const extra = SECTOR_ACCOUNTS[sector] ?? []

  const seen = new Set(base.map(a => a.code))
  const merged = [...base]

  for (const acc of extra) {
    if (!seen.has(acc.code)) {
      merged.push(acc)
      seen.add(acc.code)
    }
  }

  return merged
}

